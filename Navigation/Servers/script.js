// DOM elements
const contentScroll = document.getElementById("contentScroll");
const channelItems = document.querySelectorAll(".channel-item");
const groupHeaders = document.querySelectorAll(".channel-group-header");

// Load channel content
function loadChannel(channelId) {
  const data = channelData[channelId];
  if (!data) return;

  const renderImage = (item, className = "", overlay = "") => {
    const imageEntries = Array.isArray(item.image)
      ? item.image
      : item.image
        ? [{ type: "image", url: item.image }]
        : [];
    const images = imageEntries
      .map((image) => {
        const imageUrl =
          image.type === "discord-emoji"
            ? `https://cdn.discordapp.com/emojis/${image.id}.png`
            : image.url;
        return imageUrl
          ? `<img src="${imageUrl}" alt="${item.name}" loading="lazy" />`
          : "";
      })
      .join("");
    const content = images || `<span>${item.name.charAt(0)}</span>`;
    return `<div class="card-image-placeholder ${className}">${content}${overlay}</div>`;
  };

  let html = `
        <div class="content-title">${data.title}</div>
        <div class="content-meta">${data.meta}</div>
      `;

  if (data.type === "grid-server") {
    html += '<div class="grid-container">';
    data.content.forEach((server) => {
      html += `
            <div class="grid-card">
              ${renderImage(server)}
              <div class="card-content">
                <h3 class="card-title">${server.name}</h3>
                <div class="card-tags">${server.tags}</div>
                <div class="card-players">${server.players}</div>
                <a href="${server.link}" target="_blank" rel="noopener noreferrer" class="card-btn">Join</a>
              </div>
            </div>
          `;
    });
    html += "</div>";
  } else if (data.type === "grid-streamer") {
    html += '<div class="grid-container">';
    data.content.forEach((streamer) => {
      const liveClass = streamer.live ? "live" : "";
      const socialLinks = streamer.social || {};
      let socialHtml = "";
      if (socialLinks.twitch)
        socialHtml += `<a href="${socialLinks.twitch}" target="_blank" rel="noopener noreferrer" title="Twitch">𝙏</a>`;
      if (socialLinks.youtube)
        socialHtml += `<a href="${socialLinks.youtube}" target="_blank" rel="noopener noreferrer" title="YouTube">▶</a>`;
      if (socialLinks.discord)
        socialHtml += `<span title="Discord">${socialLinks.discord}</span>`;
      if (socialLinks.twitter)
        socialHtml += `<a href="${socialLinks.twitter}" target="_blank" rel="noopener noreferrer" title="Twitter">𝕏</a>`;
      if (socialLinks.instagram)
        socialHtml += `<a href="${socialLinks.instagram}" target="_blank" rel="noopener noreferrer" title="Instagram">📷</a>`;
      if (socialLinks.tiktok)
        socialHtml += `<a href="${socialLinks.tiktok}" target="_blank" rel="noopener noreferrer" title="TikTok">♪</a>`;

      html += `
            <div class="grid-card streamer-card">
              ${renderImage(streamer, `streamer-avatar ${liveClass}`, streamer.live ? '<div class="live-badge">LIVE</div>' : "")}
              <div class="card-content">
                <h3 class="card-title">${streamer.name}</h3>
                <div class="card-platform">${streamer.platform}</div>
                <div class="card-followers">${streamer.followers}</div>
                <div class="card-social">
                  ${socialHtml}
                </div>
              </div>
            </div>
          `;
    });
    html += "</div>";
  } else if (data.type === "grid-community") {
    html += '<div class="grid-container">';
    data.content.forEach((community) => {
      html += `
            <div class="grid-card">
              ${renderImage(community, "community-image")}
              <div class="card-content">
                <h3 class="card-title">${community.name}</h3>
                <div class="card-followers">${community.members}</div>
                <a href="${community.link}" target="_blank" rel="noopener noreferrer" class="card-btn">Join</a>
              </div>
            </div>
          `;
    });
    html += "</div>";
  }

  contentScroll.innerHTML = html;
}

// Channel item click
channelItems.forEach((item) => {
  item.addEventListener("click", () => {
    channelItems.forEach((i) => i.classList.remove("active"));
    item.classList.add("active");
    const channelId = item.getAttribute("data-channel");
    loadChannel(channelId);
  });
});

// Toggle category
groupHeaders.forEach((header) => {
  header.addEventListener("click", () => {
    header.classList.toggle("collapsed");
    const listId = header.nextElementSibling.id;
    document.getElementById(listId).classList.toggle("collapsed");
  });
});

// Load default channel
loadChannel("fivem-servers");
